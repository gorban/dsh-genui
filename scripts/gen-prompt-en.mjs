// Generate the English GenUI card-authoring prompt shipped by this fork.
//
// Why this exists: the upstream `@opentiny/genui-sdk-core` `genPrompt()` emits a
// Chinese-only prompt. Its dist carries no English template, its material
// metadata carries only `zh_CN` (no `en_US`), and `IGenPromptOptions` has no
// locale/language field — there is no supported way to ask the SDK for English.
//
// So this fork ships its own prompt. The script calls `genPrompt()` once, applies
// the reviewed translation maps in `prompt-translations/`, and asserts that no
// CJK character survives. The result is frozen into `src/prompt/genui-prompt.en.ts`,
// which is what the plugin registers at runtime — no SDK call and no translation
// work happens in the shipped code path.
//
// Re-run after bumping @opentiny/genui-sdk-core or its materials package:
//   node scripts/gen-prompt-en.mjs
//
// A mismatch is expected after an SDK upgrade (the template moves, so a line-map
// index no longer matches); fix the maps rather than relaxing the assertions.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { genPrompt } from '@opentiny/genui-sdk-core'
import { materialsMeta } from '@opentiny/genui-sdk-materials-vue-opentiny-vue/meta'

const HERE = dirname(fileURLToPath(import.meta.url))
const MAPS = join(HERE, 'prompt-translations')
const OUT = join(HERE, '..', 'src', 'prompt', 'genui-prompt.en.ts')
const CJK = /[\u4e00-\u9fff]/

const units = JSON.parse(readFileSync(join(MAPS, 'string-units.json'), 'utf8'))
const english = JSON.parse(readFileSync(join(MAPS, 'string-en.json'), 'utf8'))
const lineMap = JSON.parse(readFileSync(join(MAPS, 'line-en.json'), 'utf8'))

if (units.length !== english.length) {
  throw new Error(`translation maps disagree: ${units.length} source strings vs ${english.length} translations`)
}
if (english.some((value) => CJK.test(value))) {
  throw new Error('a translation map value still contains Chinese')
}

// Must match the custom actions the plugin registers, or the regenerated prompt
// would describe a different tool surface than the runtime exposes.
const customActions = [
  {
    name: 'continueChat',
    description:
      'Continue the conversation (e.g. form submit). Pass a short message only; the host appends the card state (formData, etc.) automatically.',
    parameters: {
      type: 'object',
      properties: {
        message: {
          type: 'string',
          description: 'Short follow-up text (button label or summary). Do not put form fields here.',
        },
      },
      required: ['message'],
    },
  },
]

const source = genPrompt('Vue', materialsMeta, { customActions })

// 1. Whole-line prose replacement. The SDK template is line-structured, so a
//    reviewed English line per source line keeps sentence structure intact.
const lines = source.split('\n')
for (const [number, replacement] of Object.entries(lineMap)) {
  const index = Number(number) - 1
  const original = lines[index]
  if (original === undefined) {
    throw new Error(`line map targets line ${number}, past the end of the generated prompt`)
  }
  const stripped = original.trim()
  if (stripped === '' || !original.includes(stripped)) {
    throw new Error(`line map entry ${number} does not line up with the generated prompt`)
  }
  if (CJK.test(replacement)) throw new Error(`line map entry ${number} is not English`)
  lines[index] = original.replace(stripped, replacement)
}
let text = lines.join('\n')

// 2. String-table replacement for Chinese inside JSON/code blocks (material
//    metadata, schema descriptions, example data). Longest first so a longer
//    phrase is never shadowed by one of its own substrings.
const pairs = units.map((zh, i) => [zh, english[i]]).sort((a, b) => b[0].length - a[0].length)
for (const [zh, en] of pairs) {
  if (text.includes(zh)) text = text.split(zh).join(en)
}

// 3. Hard gate: the shipped prompt must contain no Chinese at all.
const survivors = text
  .split('\n')
  .map((line, i) => [i + 1, line])
  .filter(([, line]) => CJK.test(line))
if (survivors.length > 0) {
  for (const [number, line] of survivors) {
    console.error(`  L${number}: ${line.slice(0, 200)}`)
  }
  throw new Error(`${survivors.length} line(s) still contain Chinese; extend the translation maps`)
}

mkdirSync(dirname(OUT), { recursive: true })
writeFileSync(
  OUT,
  [
    '/**',
    ' * GENERATED by scripts/gen-prompt-en.mjs — do not edit by hand.',
    ' *',
    ' * The English GenUI card-authoring prompt. Upstream @opentiny/genui-sdk-core is',
    ' * Chinese-only (no locale option, no en_US material metadata, no English',
    ' * template in its dist), so this fork freezes a reviewed English prompt here',
    ' * instead of calling genPrompt() at runtime.',
    ' *',
    ' * Regenerate with `node scripts/gen-prompt-en.mjs` after upgrading the SDK or',
    ' * its materials package.',
    ' */',
    `export const GENUI_PROMPT_EN: string = ${JSON.stringify(text)}`,
    '',
  ].join('\n'),
)
console.log(`wrote ${OUT}`)
console.log(`${text.length} chars, 0 CJK, ${text.split('\n').length} lines`)